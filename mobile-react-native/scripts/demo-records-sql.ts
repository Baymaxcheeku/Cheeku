/*
 * Writes supabase/manual/demo-records.sql: one sample record of every type,
 * for looking at each record page on a real account.
 *
 *   ../node_modules/.bin/tsx scripts/demo-records-sql.ts
 *
 * The samples are the preview reader's own (lib/ai/mock/fixtures/records.ts),
 * so the SQL, the tests and the upload flow all show the same documents.
 * Fixture dates are generated around 1990-06-15 and shifted to "today" when
 * the SQL runs, so countdowns (days left, next dose, renewal) always read
 * right. 1990 can never collide with a shifted date.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { extractFromFile } from "../src/lib/ai/mock/extract";
import { entityRows } from "../src/lib/records/reading";
import { DOC_TYPES } from "../src/lib/records/types";

const BASE = "1990-06-15";
const q = (s: string | null | undefined) => (s === null || s === undefined ? "null" : `'${s.replace(/'/g, "''")}'`);

const rows: string[] = [];
for (const type of DOC_TYPES) {
  if (type === "other") continue;
  const x = extractFromFile(`demo-${type}.pdf`, 4096, type, BASE);
  const extraction = { title: x.title, fields: x.fields, values: x.values, details: x.details };
  const entities = entityRows(x);
  rows.push(
    `  (${q(type)}, ${q(x.title)}, ${q(x.eventDate)}, ${q(x.facility)}, ${q(x.doctor)}, ${x.confidence}, ${q(JSON.stringify(extraction))}, ${q(JSON.stringify(entities))})`,
  );
}

const sql = `-- DEMO RECORDS, for the Supabase SQL Editor. Not a migration.
--
-- Adds one sample record of every kind (lab report, prescription, scan,
-- discharge summary, medication list, vaccination, insurance, bill,
-- consultation invoice, booking invoice) to ONE account, so every record
-- page can be seen on a phone. Needs migration 0028 applied first.
--
-- 1. Put your sign-in email on the line marked EMAIL below.
-- 2. Paste all of it into the SQL Editor and press Run.
--
-- Everything here is invented sample data, marked DEMO-RECORDS. The
-- vaccination goes to your first family member if you have one, everything
-- else to you. There's no scanned page behind these, so "Original" shows as
-- unavailable. To remove them all again, run the last statement at the
-- bottom on its own.
--
-- Generated by mobile-react-native/scripts/demo-records-sql.ts. Do not edit.

do $$
declare
  v_email text := 'you@example.com';  -- EMAIL: your sign-in email
  v_user uuid;
  v_me uuid;
  v_other uuid;
  v_shift int := current_date - date '${BASE}';
  r record;
  v_doc uuid;
  v_ext jsonb;
  v_ents jsonb;
  v_profile uuid;
  m text;
begin
  select id into v_user from auth.users where lower(email) = lower(v_email);
  if v_user is null then
    raise exception 'No account with the email %. Put your sign-in email on the EMAIL line.', v_email;
  end if;
  select id into v_me from profiles where user_id = v_user and is_primary;
  select id into v_other from profiles
  where user_id = v_user and not is_primary and id in (select covered_profile_ids(v_user))
  order by created_at limit 1;

  for r in
    select * from (values
${rows.join(",\n")}
    ) as t (doc_type, title, event_date, facility, doctor, confidence, extraction, entities)
  loop
    -- Move every 1990 date to the same distance from today.
    v_ext := r.extraction::jsonb;
    v_ents := r.entities::jsonb;
    for m in select distinct (regexp_matches(r.extraction || r.entities || r.event_date, '1990-\\d{2}-\\d{2}', 'g'))[1] loop
      v_ext := replace(v_ext::text, m, to_char(m::date + v_shift, 'YYYY-MM-DD'))::jsonb;
      v_ents := replace(v_ents::text, m, to_char(m::date + v_shift, 'YYYY-MM-DD'))::jsonb;
    end loop;

    v_profile := case when r.doc_type = 'vaccination' then coalesce(v_other, v_me) else v_me end;
    v_doc := gen_random_uuid();

    insert into documents (id, profile_id, user_id, storage_path, mime_type, doc_type, status, event_date, facility, doctor, confidence, raw_text, extraction)
    values (v_doc, v_profile, v_user, v_user || '/' || v_profile || '/demo-' || v_doc || '.pdf', 'application/pdf',
            r.doc_type, 'filed', r.event_date::date + v_shift, r.facility, r.doctor, r.confidence, 'DEMO-RECORDS sample', v_ext);

    insert into entities (profile_id, user_id, document_id, kind, name, canonical_name, value, value_text, unit, ref_range, flag, event_date)
    select v_profile, v_user, v_doc, e ->> 'kind', e ->> 'name', e ->> 'canonical_name', (e ->> 'value')::numeric,
           e ->> 'value_text', e ->> 'unit', e ->> 'ref_range', e ->> 'flag', r.event_date::date + v_shift
    from jsonb_array_elements(v_ents) e;
  end loop;

  -- The samples arrive quietly: no "is filed" or "needs a look" in the inbox.
  delete from notifications
  where user_id = v_user and document_id in (select id from documents where user_id = v_user and raw_text = 'DEMO-RECORDS sample');
end $$;

-- To remove every demo record again, run this line on its own:
-- delete from documents where raw_text = 'DEMO-RECORDS sample';
`;

const out = resolve(__dirname, "../../supabase/manual/demo-records.sql");
writeFileSync(out, sql);
console.log(`wrote ${out}`);
