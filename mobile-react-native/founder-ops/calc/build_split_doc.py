"""Writes library/seed-split-dilution-model.md from split.py so the tables never drift from the maths."""
import os
from split import convert, min_cap, FOUNDERS_PRE

I, X, TOTAL = 5.0, 21.0, 26.0
CAP, DISC = 85, 0.10
OUT = os.path.join(os.path.dirname(__file__), "..", "library", "seed-split-dilution-model.md")

def p(x, n=1): return f"{x*100:.{n}f}%"
def cr(x): return f"₹{x:,.0f} cr"

def flag(D):
    s = f"{D*100:.1f}"
    if D > 0.23 + 1e-9: return s + " !"
    if D <= 0.20 + 1e-9: return "**" + s + "** *"
    return "**" + s + "**"

def solve_x(P, C, d, D):
    lo, hi = 0.0, 60.0
    for _ in range(80):
        mid = (lo + hi) / 2
        if convert(I, C, d, P + mid, mid)["D"] <= D: lo = mid
        else: hi = mid
    return lo

NAMED = [("Bear", 116), ("Base", 130), ("Bull", 153)]
L = []
w = L.append

w("# Seed split: ₹5 cr angel iSAFE plus ₹21 cr institutional round")
w("")
w("The question: what valuation do we pitch the angels, so that the angels and the Q1 2027 institutional cheque together dilute us by no more than 23%, and ideally 18 to 20%.")
w("")
w("Every table below is generated by `founder-ops/calc/split.py` and checked against a share-by-share cap table. Rerun `python3 calc/build_split_doc.py` from the founder-ops folder to refresh it after changing an input.")
w("")

# ---------------------------------------------------------------- answer
w("## The answer")
w("")
w(f"**Pitch the angels a ₹{CAP} crore post-money cap with a {int(DISC*100)}% discount.** On the iSAFE the angels convert at whichever is lower, the cap price or the discount price, inside the institutional round.")
w("")
w(f"- It is the lowest round-number cap that keeps total seed dilution under 23% when the institutional round prices at our bear case (₹116 cr post-money). The exact floor is ₹{min_cap(I, X, 116, .23):.1f} cr.")
w("- At our base case (₹130 cr post-money) the total is about 21%. At the bull case (₹153 cr) it is under 19%.")
w("- Angels still get a real step-up: roughly 1.1x if the round is weak, 1.3x at base and 1.5x at bull, on top of being first in.")
w("- My earlier suggestion of a ₹75 cr cap was made before 23% became a hard ceiling. It only holds the ceiling if the institutional post-money is at least ₹120 cr. At ₹116 cr it gives 23.6%.")
w("")
hdr = "| Case | Institutional post-money | VC pre-money | VC gets | Angels get | Total seed dilution | If angels paid the round price | Cost of the angel discount | Founders after seed | Pool after seed | Angel step-up |"
w(hdr)
w("|---|---|---|---|---|---|---|---|---|---|---|")
for name, V in NAMED:
    r = convert(I, CAP, DISC, V, X)
    w(f"| {name} | {cr(V)} | {cr(r['P'])} | {p(r['vc'])} | {p(r['angel'])} | **{p(r['D'])}** | {p(r['par'])} | {r['tax']*100:.1f} pts | {p(r['founders'])} | {p((1-FOUNDERS_PRE)*(1-r['D']))} | {r['stepup']:.2f}x |")
w("")
w("Post-money here means the value of the company the moment the whole seed has closed, angels included. VC pre-money is that number less the ₹21 cr cheque, and the angels' converted shares sit inside it.")
w("")

# ---------------------------------------------------------------- what it depends on
w("## What the 23% ceiling really depends on")
w("")
w("Most of the dilution is set by the institutional valuation, not by the angel cap. Raising ₹26 cr at a post-money of V dilutes us by 26 / V even if the angels paid exactly the round price. The angel cap only adds a small premium on top of that.")
w("")
w("| Total dilution target | Post-money needed (angels at round price) | VC pre-money for the ₹21 cr |")
w("|---|---|---|")
for D in (.23, .20, .18):
    V = TOTAL / D
    w(f"| {int(D*100)}% | {cr(V)} | {cr(V - X)} |")
w("")
w("So there are two honest statements to make to ourselves:")
w("")
w("1. **The 23% ceiling needs an institutional post-money of about ₹113 cr or more, whatever cap we give the angels.** Below that the only fix is a smaller institutional cheque (see the cheque table further down).")
w("2. **The 18 to 20% band is a valuation outcome, not a cap outcome.** Twenty percent needs ₹130 cr post-money with no angel discount at all. With the ₹85 cr cap it needs about ₹140 cr post-money (VC pre-money near ₹119 cr). The cap decides how much of the gap we give away to angels, usually 1 to 3 points.")
w("")

# ---------------------------------------------------------------- assumptions
w("## Inputs and assumptions")
w("")
w("- Round: ₹26 cr in two parts, ₹5 cr angels on iSAFE now, ₹21 cr institutional in Q1 2027. (At about $2.7M the implied rate is roughly ₹96 a dollar, so quote angels in rupees and check the rate before putting dollars in writing.)")
w("- Before the seed the founders hold 90% and the option pool 10%, the same basis as the financial model and `our-story.md`. No extra pool top-up at the seed; the model adds 5% at the Series A.")
w("- The iSAFE is drafted on a post-money cap (TrailBlazer's read of the 100X.VC template). If your lawyer's template uses a pre-money cap, subtract ₹5 cr from every cap in this document to get the equivalent.")
w("- The iSAFE converts inside the institutional pre-money, which is how institutions price SAFEs. Make the term sheet say so in writing, and quote the round to us as a post-money.")
w("- Scenario valuations are the financial model's seed cases: bear ₹116 cr, base ₹130 cr, bull ₹153 cr post-money. They are our planning numbers, not a market read. Nobody can promise a Q1 2027 valuation.")
w("")

# ---------------------------------------------------------------- formulas
w("## How the numbers work")
w("")
w("```")
w("I = angel cheque (5)   X = institutional cheque (21)   C = angel cap   d = discount")
w("V = post-money after the whole seed   P = V - X = institutional pre-money")
w("")
w("angel share if the cap binds       = (I / C) x (P / V)")
w("angel share if the discount binds  = (I / (1 - d)) / V")
w("angel share at the round price     = I / V          (the floor)")
w("angel share                        = the largest of the three")
w("institutional share                = X / V")
w("total seed dilution                = angel share + institutional share")
w("founders after seed                = 90% x (1 - total dilution)")
w("angel step-up                      = angel share x V / I")
w("lowest cap that holds a ceiling D  = I x (V - X) / (D x V - X)")
w("```")
w("")
w("The cap binds when the institutional pre-money is more than about 11% above the cap (that is, when the cap price is below the discount price). Below that the discount takes over and gives angels a small floor.")
w("")

# ---------------------------------------------------------------- grid
w("## Total dilution by cap and institutional post-money")
w("")
w(f"Angel cheque ₹5 cr, institutional cheque ₹21 cr, {int(DISC*100)}% discount. Bold means inside the 23% ceiling. A star means 20% or less. An exclamation mark means over the ceiling.")
w("")
Vs = [113, 116, 120, 125, 130, 140, 150, 160]
caps = [70, 75, 80, 85, 90, 95, 100, 110]
w("| Cap (post-money) | " + " | ".join(f"V {v}" for v in Vs) + " |")
w("|---|" + "---|" * len(Vs))
for C in caps:
    row = []
    for V in Vs:
        row.append(flag(convert(I, C, DISC, V, X)["D"]))
    mark = " (recommended)" if C == CAP else ""
    w(f"| ₹{C} cr{mark} | " + " | ".join(row) + " |")
w("")
w("Angel step-up on the same grid (how much the angels' money is worth the moment the round closes):")
w("")
w("| Cap (post-money) | " + " | ".join(f"V {v}" for v in Vs) + " |")
w("|---|" + "---|" * len(Vs))
for C in caps:
    w(f"| ₹{C} cr | " + " | ".join(f"{convert(I, C, DISC, V, X)['stepup']:.2f}x" for V in Vs) + " |")
w("")

# ---------------------------------------------------------------- min cap
w("## Lowest cap that holds the ceiling")
w("")
w(f"For each institutional post-money, the lowest cap we can give the angels and still land under the target (with a {int(DISC*100)}% discount in the note). \"None\" means no cap can get there, because the round price plus the 10% discount floor is already over target. Dropping the discount lowers that floor.")
w("")
w("| Institutional post-money | Hold 23% | Hold 22% | Hold 21% | Hold 20% |")
w("|---|---|---|---|---|")
for V in (113, 116, 120, 125, 130, 140, 150):
    cells = []
    for D in (.23, .22, .21, .20):
        floor = (X + I / (1 - DISC)) / V
        c = min_cap(I, X, V, D)
        if floor > D + 1e-9 or c == float("inf") or c > 400: cells.append("None")
        elif c <= 0: cells.append("Any")
        else: cells.append(f"₹{c:.0f} cr")
    w(f"| {cr(V)} | " + " | ".join(cells) + " |")
w("")
w("Read it as: if we expect the institutional round to land at ₹120 cr or better, ₹75 cr is enough to hold 23%. We recommend ₹85 cr because it still holds when the round lands as low as ₹116 cr, which is the bear case.")
w("")

# ---------------------------------------------------------------- options
w("## Five cap options side by side")
w("")
w(f"{int(DISC*100)}% discount in every option. Total seed dilution and angel step-up in each of our three cases.")
w("")
w("| Cap | Bear V 116 | Base V 130 | Bull V 153 | Holds 23% in bear? | Angel step-up bear / base / bull | Verdict |")
w("|---|---|---|---|---|---|---|")
verd = {75: "Strongest angel pitch, breaches the ceiling if the round is weak",
        80: "Breaches by a hair in the bear case",
        85: "Holds the ceiling in all three cases, step-up still above 1.1x",
        90: "Safer for us, thinner pitch to angels",
        100: "Safest for us, step-up near 1.1x, angels will push back"}
for C in (75, 80, 85, 90, 100):
    rs = [convert(I, C, DISC, V, X) for _, V in NAMED]
    ok = "Yes" if rs[0]["D"] <= .23 + 1e-9 else "No"
    w(f"| ₹{C} cr | {flag(rs[0]['D'])} | {flag(rs[1]['D'])} | {flag(rs[2]['D'])} | {ok} | {rs[0]['stepup']:.2f}x / {rs[1]['stepup']:.2f}x / {rs[2]['stepup']:.2f}x | {verd[C]} |")
w("")
w("One tactic to consider: a tiered close. The first ₹2 cr of angels at a ₹80 cr cap, the remaining ₹3 cr at ₹90 cr. It rewards the people who commit first, and the blended result is almost identical to a single ₹85 cr cap (5.83% against 5.88% before the institutional round dilutes it). The iSAFE documents are separate per investor, so it needs no special drafting, but tell every angel the structure up front.")
w("")

# ---------------------------------------------------------------- cap table walk
w("## Base case, share by share")
w("")
S0 = 1_000_000
safe = S0 * (I / CAP) / (1 - I / CAP)
pre_total = S0 + safe
Vb = 130
Pb = Vb - X
pps = Pb * 1e7 / pre_total
cap_price = CAP * 1e7 / pre_total
vc_sh = X * 1e7 / pps
post_total = pre_total + vc_sh
w(f"Illustrative share counts on a 10,00,000 share base. Cap price ₹{cap_price:,.0f} a share, institutional price ₹{pps:,.0f} a share (institutional pre-money {cr(Pb)}, post-money {cr(Vb)}).")
w("")
w("| Holder | Before seed | After angels convert | After institutional round | % at the end |")
w("|---|---|---|---|---|")
rows = [("Founders (3)", 900_000, 900_000), ("Option pool", 100_000, 100_000), ("Angels (iSAFE converts)", 0, safe), ("Institutional investors", 0, vc_sh)]
for nm, b, a in rows:
    after = a
    pre_pct = (b / S0) if nm in ("Founders (3)", "Option pool") else 0
    mid = a if nm != "Institutional investors" else 0
    w(f"| {nm} | {int(b):,} | {int(mid):,} | {int(after):,} | {after/post_total*100:.2f}% |")
w(f"| **Total** | {S0:,} | {int(pre_total):,} | {int(post_total):,} | 100.00% |")
w("")
w(f"Check: angels {safe/post_total*100:.2f}% plus institutions {vc_sh/post_total*100:.2f}% is {((safe+vc_sh)/post_total)*100:.2f}% total seed dilution, founders {900_000/post_total*100:.2f}%.")
w("")

# ---------------------------------------------------------------- offers lookup
w("## If the institution quotes a different number")
w("")
w(f"Institutions quote a pre-money. Here is what each quote does to us at the recommended terms (₹{CAP} cr cap, {int(DISC*100)}% discount, ₹21 cr cheque).")
w("")
w("| VC pre-money quote | Post-money | Total dilution | Founders after seed | Angel step-up | Status |")
w("|---|---|---|---|---|---|")
for P in (85, 90, 95, 100, 105, 110, 115, 120, 130):
    V = P + X
    r = convert(I, CAP, DISC, V, X)
    st = "Over ceiling" if r["D"] > .23 + 1e-9 else ("In the 18 to 20% band" if r["D"] <= .20 + 1e-9 else "Inside ceiling")
    w(f"| {cr(P)} | {cr(V)} | {r['D']*100:.1f}% | {p(r['founders'])} | {r['stepup']:.2f}x | {st} |")
w("")
w("When the quote is over the ceiling, shrink the institutional cheque rather than accept the dilution. The largest cheque that still holds each target at the recommended terms:")
w("")
w("| VC pre-money quote | Largest cheque for 23% | Seed total | Largest cheque for 20% | Seed total |")
w("|---|---|---|---|---|")
for P in (85, 90, 95, 100, 105, 110, 120):
    x23 = solve_x(P, CAP, DISC, .23); x20 = solve_x(P, CAP, DISC, .20)
    w(f"| {cr(P)} | {cr(x23)} | {cr(I + x23)} | {cr(x20)} | {cr(I + x20)} |")
w("")
w("The cheque shrinks as the valuation falls, so the cost of a weak round shows up as a smaller seed, not as a bigger bite out of us. That is the lever to hold in reserve.")
w("")

