import { FileText, Search, TriangleAlert, type LucideIcon } from "lucide-react";

import { Drift, PulseRing, Settle } from "@/components/ui/motion";
import { cn } from "@/lib/cn";

/*
 * Artwork for the About screen.
 *
 * REBUILT 2026-08-01. The previous `AnxietyScene` drew its own person: a flat
 * torso, a hand-painted face at `#f5d7c4`, black swept hair, downturned brows.
 * Three things were wrong with it. It depicted one specific ethnicity and
 * gender as "the anxious user" on a page arguing the product is for everyone.
 * It was the only hand-drawn human in an app whose every other face comes from
 * one generator, so it read as clip art that had wandered in. And a crude face
 * rendering worry is a weak way to say "worry" when the app can show the
 * actual thing that causes it.
 *
 * What replaced it argues instead of illustrates: the reader's own face,
 * ringed by the contradictory results a symptom search returns, resolving into
 * one cited answer. Built from the app's real card vocabulary — same radii,
 * shadows and tints as the screens it describes — rather than from SVG shapes
 * that only resemble them.
 */

type ArtProps = { className?: string };

/** The four voices a 2am symptom search actually returns. */
const NOISE = [
  { text: "Could be nothing…", tone: "quiet" },
  { text: "See a doctor immediately", tone: "loud" },
  { text: "12 possible causes", tone: "quiet" },
] as const;

/**
 * The spiral: one face, the noise around it, and the answer underneath.
 *
 * Reads top to bottom as the argument itself — contradictory results, then a
 * single answer that names its source. The avatar is generated by the same
 * `micah` pipeline as every profile in the app, so the person on this page is
 * visibly the same species of person as the reader's own family.
 */
export function SpiralScene({ face, className }: ArtProps & { face: string }) {
  return (
    <div className={cn("relative px-4 pb-1 pt-2", className)}>
      <div className="relative mx-auto flex w-full max-w-[300px] flex-col items-center">
        {/*
         * Noise, fanned above the face and deliberately contradictory. Each
         * chip keeps drifting on its own phase and never settles, which is the
         * whole point: the searching does not resolve on its own.
         */}
        <div className="relative z-10 flex w-full flex-col items-center gap-1.5">
          {NOISE.map(({ text, tone }, i) => (
            <Drift
              key={text}
              delay={i * 0.12}
              className={cn(
                i === 0 && "-rotate-3 self-start",
                i === 1 && "rotate-2 self-end",
                i === 2 && "-rotate-1",
              )}
            >
              <span className="flex items-center gap-1.5 rounded-pill bg-surface px-3 py-1.5 shadow-e1">
                {tone === "loud" ? (
                  <TriangleAlert size={11} className="shrink-0 text-caution" aria-hidden />
                ) : (
                  <Search size={11} className="shrink-0 text-ink-300" aria-hidden />
                )}
                <span
                  className={cn(
                    "text-[10.5px] leading-none",
                    tone === "loud" ? "font-semibold text-ink-900" : "text-ink-500",
                  )}
                >
                  {text}
                </span>
              </span>
            </Drift>
          ))}
        </div>

        {/* The reader, in the middle of it, with the search still radiating. */}
        <div className="relative mt-1 grid place-items-center">
          <span
            aria-hidden
            className="absolute h-24 w-24 rounded-pill bg-brand-200/50 blur-2xl"
          />
          <PulseRing />
          {/* eslint-disable-next-line @next/next/no-img-element -- inline data URI */}
          <img
            src={face}
            alt=""
            className="relative h-[72px] w-[72px] rounded-pill bg-surface object-cover shadow-e2 ring-[3px] ring-white"
          />
        </div>

        {/* The resolution. Brand-filled so it is visibly the one thing on this
            picture that is not noise, and the only one that holds still.
            Clears the face rather than overlapping it: pulled up, the card cut
            the chin off and the person read as damaged rather than as the
            subject. */}
        <Settle className="relative mt-2.5 w-full rounded-tile bg-brand-600 p-3 shadow-e2">
          <p className="text-[11.5px] font-semibold leading-snug text-white">
            Your haemoglobin is 10.4, below the 12–15 printed on this report.
          </p>
          <p className="mt-1.5 flex items-center gap-1 text-[9.5px] font-semibold text-brand-200">
            <FileText size={9} aria-hidden />
            Complete blood count · 27 Jul
          </p>
        </Settle>
      </div>
    </div>
  );
}

