"use client";

import { useState } from "react";
import { ChevronRight, Lock, Plus, UserRoundPlus } from "lucide-react";

import { AddMemberSheet } from "@/components/app/add-member-sheet";
import { Paywall } from "@/components/billing/paywall";
import { cn } from "@/lib/cn";
import { allowsFamily, seatsFor, type Tier } from "@/lib/billing/plans";
import type { ActiveProfile } from "@/lib/profiles/context";

/*
 * The Family block on the Profile screen, in both of its states.
 *
 * ON THE FAMILY PLAN it is what it looks like: the real members, the active one
 * ringed, and a working "Add member".
 *
 * ON FREE OR SOLO it is the locked version from the H-Solo frame — blurred
 * faces behind padlocks, and a plain statement that family access is part of
 * the Family plan. Two things about that are deliberate:
 *
 *   The blurred faces are GENERATED placeholders, not real people. Blurring an
 *   actual member's avatar to sell a plan would mean holding their data and
 *   showing it back as bait; these are decorative, seeded from fixed strings,
 *   and represent nobody.
 *
 *   The primary profile is NOT locked. It is the reader's own, they already
 *   have it, and dimming it to make the upsell look bigger would be a lie about
 *   what they can access.
 */

export function FamilySection({
  profiles,
  activeId,
  tier,
  lockedFaces,
}: {
  profiles: readonly ActiveProfile[];
  activeId: string;
  tier: Tier;
  /*
   * Stand-in faces for the locked slots, generated by the server (the avatar
   * renderer needs `Buffer`). Same generator as every real profile picture, so
   * the locked row looks like the row it is promising — but seeded on fixed
   * strings, so it depicts nobody.
   */
  lockedFaces: readonly string[];
}) {
  const [addOpen, setAddOpen] = useState(false);
  const [paywallOpen, setPaywallOpen] = useState(false);

  const unlocked = allowsFamily(tier);
  const seats = seatsFor(tier);
  const primary = profiles.find((p) => p.isPrimary) ?? profiles[0];

  // Enough locked slots to reach what the Family plan would cover, so the
  // number on screen matches the number in the pitch.
  const lockedSlots = Math.max(0, seatsFor("family") - 1);

  return (
    <>
      <section className="mt-6">
        {/*
         * The group label sits outside the card, in the page's own margin, the
         * way every other group on this screen now does. Inside-the-card
         * headings made each block look like a page of its own and cost a row
         * of vertical space each time.
         */}
        <div className="flex items-baseline justify-between px-5">
          <h2 className="text-[12px] font-bold uppercase tracking-wide text-ink-300">Family</h2>
          {unlocked ? (
            <span className="text-[11.5px] font-medium text-ink-500">
              {profiles.length} of {seats}
            </span>
          ) : (
            /* "Family plan" alone read as a label rather than a state — it was
               not clear whether it described what the reader had or what they
               were missing. The padlock says which. */
            <span className="flex items-center gap-1 text-[11.5px] font-medium text-ink-500">
              <Lock size={11} aria-hidden />
              Locked
            </span>
          )}
        </div>

        <div className="mx-5 mt-2 overflow-hidden rounded-card bg-surface shadow-e1">
        <ul className="grid grid-cols-5 gap-2 p-3">
          {/* The reader's own profile, always real and always unlocked. */}
          {primary ? (
            <li>
              <div
                className={cn(
                  "flex flex-col items-center gap-1 rounded-tile p-1.5",
                  primary.id === activeId && "bg-brand-50 ring-1 ring-brand-200",
                )}
              >
                {/* eslint-disable-next-line @next/next/no-img-element -- inline data URI */}
                <img
                  src={primary.avatar}
                  alt=""
                  className="h-11 w-11 rounded-pill bg-canvas object-cover"
                />
                <span className="w-full truncate text-center text-[10.5px] font-semibold text-ink-900">
                  {primary.name}
                </span>
                <span className="text-[9.5px] font-medium text-brand-600">You</span>
              </div>
            </li>
          ) : null}

          {unlocked
            ? profiles
                .filter((p) => p.id !== primary?.id)
                .map((member) => (
                  <li key={member.id}>
                    <div
                      className={cn(
                        "flex flex-col items-center gap-1 rounded-tile p-1.5",
                        member.id === activeId && "bg-brand-50 ring-1 ring-brand-200",
                      )}
                    >
                      {/* eslint-disable-next-line @next/next/no-img-element -- inline data URI */}
                      <img
                        src={member.avatar}
                        alt=""
                        className="h-11 w-11 rounded-pill bg-canvas object-cover"
                      />
                      <span className="w-full truncate text-center text-[10.5px] font-semibold text-ink-900">
                        {member.name}
                      </span>
                      <span className="w-full truncate text-center text-[9.5px] text-ink-500">
                        {member.relationship ?? "Family"}
                      </span>
                    </div>
                  </li>
                ))
            : Array.from({ length: lockedSlots }, (_, i) => (
                <li key={`locked-${i}`}>
                  <button
                    type="button"
                    onClick={() => setPaywallOpen(true)}
                    aria-label="Family access is part of the Family plan"
                    className="tappable flex w-full flex-col items-center gap-1 rounded-tile p-1.5 active:scale-95"
                  >
                    <span className="relative grid h-11 w-11 place-items-center">
                      {/* A real generated face, blurred — the frame's treatment.
                          Blurred rather than hidden so the row reads as "people
                          could be here", which is what is being sold. */}
                      {/* eslint-disable-next-line @next/next/no-img-element -- inline data URI */}
                      <img
                        src={lockedFaces[i % Math.max(1, lockedFaces.length)]}
                        alt=""
                        className="absolute inset-0 h-full w-full rounded-pill object-cover blur-[4px]"
                        aria-hidden
                      />
                      <span className="relative grid h-6 w-6 place-items-center rounded-pill bg-surface/90 text-ink-500 shadow-e1">
                        <Lock size={12} aria-hidden />
                      </span>
                    </span>
                    <span className="h-2.5 w-10 rounded-pill bg-line blur-[2px]" aria-hidden />
                    <span className="h-2 w-7 rounded-pill bg-line/70 blur-[2px]" aria-hidden />
                  </button>
                </li>
              ))}

          <li>
            <button
              type="button"
              onClick={() => (unlocked ? setAddOpen(true) : setPaywallOpen(true))}
              className="tappable flex w-full flex-col items-center gap-1 rounded-tile border border-dashed border-brand-200 p-1.5 active:scale-95"
            >
              <span className="grid h-11 w-11 place-items-center rounded-pill bg-brand-50 text-brand-600">
                {unlocked ? <Plus size={18} aria-hidden /> : <Lock size={16} aria-hidden />}
              </span>
              <span className="text-[10px] font-semibold leading-tight text-brand-700">Add</span>
              <span className="text-[9.5px] leading-tight text-brand-600">member</span>
            </button>
          </li>
        </ul>

        {/*
         * One row, not a card inside a card. The old version nested a
         * brand-tinted card with its own icon tile, heading, body and button
         * inside this card — three container levels deep, and its "View plans"
         * was the second of two identical CTAs in the same block. This is a
         * plain row on the same surface, and it is the only upsell here.
         */}
        {!unlocked ? (
          <button
            type="button"
            onClick={() => setPaywallOpen(true)}
            className="tappable flex w-full items-center gap-3 border-t border-line p-3.5 text-left active:bg-brand-50"
          >
            <span className="grid h-10 w-10 shrink-0 place-items-center rounded-tile bg-brand-50 text-brand-600">
              <UserRoundPlus size={18} aria-hidden />
            </span>
            <span className="min-w-0 flex-1">
              <span className="block text-[13.5px] font-semibold text-ink-900">
                Add up to {seatsFor("family")} people
              </span>
              <span className="mt-0.5 block text-[11.5px] leading-snug text-ink-500">
                Switch between them and keep every record separate.
              </span>
            </span>
            <ChevronRight size={17} className="shrink-0 text-ink-300" aria-hidden />
          </button>
        ) : null}
        {/*
         * Nothing follows the grid on the family plan: the "+" tile in the row
         * above already opens the add sheet, and a second row that opened the
         * same sheet was the same duplication this pass exists to remove.
         */}
        </div>
      </section>

      {addOpen ? (
        <AddMemberSheet
          tier={tier}
          memberCount={profiles.length}
          onClose={() => setAddOpen(false)}
          onBack={() => setAddOpen(false)}
        />
      ) : null}

      <Paywall
        open={paywallOpen}
        reason="family"
        onClose={() => setPaywallOpen(false)}
        onActivated={() => setPaywallOpen(false)}
      />
    </>
  );
}
